  0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,
  0x42, 0x60, 0x82,
]);

/// Serves every map tile from memory.
///
/// `flutter_map`'s default provider goes to tile.openstreetmap.org through a
/// retrying HTTP client: in a widget test that means real network calls, a wall
/// of `ClientException` noise, and backoff timers that can outlive the test.
/// Override `locationTileProviderProvider` with this in any test that renders a
/// map.
class FakeTileProvider extends TileProvider {
  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) =>
      MemoryImage(_pixel);
}
